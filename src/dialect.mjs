const DIALECTS = ["tasm", "gasm80", "native"];

function add(scores, evidence, dialect, points, message) {
  scores[dialect] += points;
  evidence.push({ dialect, points, message });
}

export function detectAssemblyDialect(source, filename = "") {
  const text = String(source);
  const scores = { tasm: 0, gasm80: 0, native: 0 };
  const evidence = [];
  const count = (pattern) => [...text.matchAll(pattern)].length;

  const dotted = count(/^\s*\.(?:org|equ|db|dw|byte|word|end)\b/gim);
  if (dotted) add(scores, evidence, "tasm", Math.min(12, 3 + dotted), `${dotted} dotted TASM directive${dotted === 1 ? "" : "s"}`);
  if (/^\s*[A-Za-z_.$?][\w.$?]*\s*:\s*\.equ\b/im.test(text)) add(scores, evidence, "tasm", 4, "TASM label: .EQU declaration");
  if (/\b[01]{4,}b\b/i.test(text) && dotted) add(scores, evidence, "tasm", 1, "binary suffix literals beside dotted data directives");
  if (/\.z80$/i.test(filename)) add(scores, evidence, "tasm", 1, ".z80 filename convention");

  const conditionals = count(/^\s*(?:if|ifdef|ifndef|else|endif)\b/gim);
  if (conditionals) add(scores, evidence, "gasm80", Math.min(8, 2 + conditionals), `${conditionals} GASM80/CVBasic conditional directive${conditionals === 1 ? "" : "s"}`);
  if (/^\s*times\s+.+\bdb\b/im.test(text)) add(scores, evidence, "gasm80", 6, "GASM80 TIMES ... DB padding");
  if (/^\s*[A-Za-z_.$?][\w.$?]*\s*:\s*(?:rb|rw)\b/im.test(text)) add(scores, evidence, "gasm80", 5, "GASM80 virtual RB/RW reservation");
  if (/\b(?:COLECO|SGM|KONAMI|CVBASIC)\b/i.test(text) && conditionals) add(scores, evidence, "gasm80", 3, "CVBasic target symbols used by conditionals");

  if (/generated by amy|amy z80|amy studio/i.test(text)) add(scores, evidence, "native", 8, "Amy-generated source marker");
  if (/^\s*(?:section|export|public)\b/im.test(text)) add(scores, evidence, "native", 2, "native-style section/export directive");

  const ranking = DIALECTS.map((dialect) => ({ dialect, score: scores[dialect] })).sort((a, b) => b.score - a.score);
  const lead = ranking[0];
  const margin = lead.score - ranking[1].score;
  const confidence = lead.score === 0 ? "unknown" : margin >= 5 ? "high" : margin >= 2 ? "medium" : "low";

  const originEvidence = [];
  let origin = "generic-z80";
  if (/\bCVBasic\b/i.test(text) || (/\bCOLECO\b/i.test(text) && conditionals)) {
    origin = "cvbasic";
    originEvidence.push("CVBasic marker or generated target conditionals");
  } else if (/generated by amy|amy z80|amy studio/i.test(text)) {
    origin = "amy-studio";
    originEvidence.push("Amy source marker");
  } else if (/Oscar Toledo CVBASIC/i.test(text)) {
    origin = "cvbasic-derived";
    originEvidence.push("CVBasic attribution comment");
  }

  return {
    dialect: confidence === "unknown" ? "native" : lead.dialect,
    confidence,
    scores,
    evidence: evidence.sort((a, b) => b.points - a.points),
    origin,
    originEvidence
  };
}
